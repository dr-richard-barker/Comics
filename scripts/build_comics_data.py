def main():
    concepts_meta = json.loads((DATA_DIR / "concepts.json").read_text(encoding="utf-8"))
    concepts_by_id = {c["id"]: c for c in concepts_meta["concepts"]}
    cast_by_id = {c["id"]: c for c in concepts_meta["cast"]}
    series_by_id = {s["id"]: s for s in concepts_meta["series"]}

    all_projects = RAW_PROJECTS + ADDITIONAL_SITE_PROJECTS

    # Verify uniqueness of IDs
    seen = set()
    deduped = []
    for p in all_projects:
        if p["id"] in seen:
            continue
        seen.add(p["id"])
        deduped.append(p)

    # Sort or number issues cleanly by series and order
    series_order = {s["id"]: s["number"] for s in concepts_meta["series"]}
    deduped.sort(key=lambda x: (series_order.get(x["series_id"], 99), all_projects.index(x)))

    catalog_comics = []
    series_counts = {}

    for idx, p in enumerate(deduped, start=1):
        sid = p["series_id"]
        series_counts[sid] = series_counts.get(sid, 0) + 1
        s_meta = series_by_id[sid]

        panels = build_panels_for_project(p, concepts_by_id, cast_by_id)
        v_tel = get_project_visual_telemetry(p)
        concept_objs = [concepts_by_id[cid] for cid in p["concepts"] if cid in concepts_by_id]
        ngss_codes = sorted(list({c["ngss"] for c in concept_objs if "ngss" in c}))

        comic_obj = {
            "issue_number": idx,
            "series_issue_number": series_counts[sid],
            "id": p["id"],
            "title": p["title"],
            "comic_title": p["comic_title"],
            "emoji": p["emoji"],
            "series_id": sid,
            "series_number": s_meta["number"],
            "series_title": s_meta["short_title"],
            "art_style": s_meta["art_style"],
            "art_style_name": s_meta["art_style_name"],
            "series_color": s_meta["color"],
            "series_accent": s_meta["accent"],
            "url": p["url"],
            "repo_url": p["repo_url"],
            "characters": p["characters"],
            "concepts": p["concepts"],
            "scene_motif": p["scene_motif"],
            "metric_badge": p["metric_badge"],
            "equation": v_tel["equation"],
            "scale_bar": v_tel["scale_bar"],
            "zoom_inset": v_tel["zoom_inset"],
            "mini_plot": v_tel["mini_plot"],
            "wonder_q": p["wonder_q"],
            "challenge": p["challenge"],
            "experiment": p["experiment"],
            "discovery": p["discovery"],
            "take_home": p["take_home"],
            "hs_detail": p.get("hs_detail", p["discovery"]),
            "activity": p["activity"],
            "ngss": " · ".join(ngss_codes),
            "panels": panels
        }
        catalog_comics.append(comic_obj)

    full_payload = {
        "title": "CoSE Science Comics: The Illustrated Space Biology Anthology",
        "subtitle": "Exploring Dr. Richard Barker's Open-Science GitHub Universe — From Quantum Spin & Leaf Boundary Layers to Lunar Farms & Astronaut Health",
        "author": "Dr. Richard J. Barker (CoSE / NASA GeneLab Plant AWG Chair)",
        "total_issues": len(catalog_comics),
        "cast": concepts_meta["cast"],
        "series": concepts_meta["series"],
        "concepts": concepts_meta["concepts"],
        "comics": catalog_comics
    }

    # Write JSON
    out_json = DATA_DIR / "comics_catalog.json"
    out_json.write_text(json.dumps(full_payload, indent=2, ensure_ascii=False), encoding="utf-8")

    # Write JS bundle for instant zero-CORS loading on file:// and GitHub Pages
    out_js = DATA_DIR / "comics_catalog.js"
    out_js.write_text(
        "/* Auto-generated by scripts/build_comics_data.py */\n"
        "window.COSE_COMICS_DATA = " + json.dumps(full_payload, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8"
    )

    print(f"Built {len(catalog_comics)} comic issues across {len(concepts_meta['series'])} series and {len(concepts_meta['concepts'])} core concepts.")
    for s in concepts_meta["series"]:
        cnt = series_counts.get(s["id"], 0)
        print(f"  - Series {s['number']} ({s['short_title']} · {s['art_style_name']}): {cnt} issues")

    if "--verify" in sys.argv:
        # Validate every comic has 5 panels, all 3 grade levels, take_home, concepts, characters, and graphic novel telemetry
        for c in catalog_comics:
            assert len(c["panels"]) == 5, f"{c['id']} does not have 5 panels"
            assert c.get("equation") and c.get("scale_bar") and c.get("mini_plot"), f"Missing graphic novel telemetry in {c['id']}"
            for pnl in c["panels"]:
                assert len(pnl.get("annotations", [])) == 4, f"Expected 4 annotations in {c['id']} panel {pnl['number']}"
                assert pnl.get("equation") and pnl.get("mini_plot"), f"Missing panel telemetry in {c['id']}"
                for lvl in ("k5", "ms", "hs"):
                    assert lvl in pnl and pnl[lvl]["dialogue"], f"Missing {lvl} dialogue in {c['id']}"
            assert c["take_home"], f"Missing take_home in {c['id']}"
            assert len(c["concepts"]) >= 2, f"Too few concepts in {c['id']}"
        print("VERIFICATION PASSED: All 114 comic schemas, 570 panels, 2,280 technical annotations, mini-plots, and equations are 100% valid.")


if __name__ == "__main__":
    main()
